#!/usr/bin/env bash
set -euo pipefail

# 1. Locate the repository root ----
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

# 2. List tracked data and temporary-file paths for inspection ----
echo "Checking Git-tracked paths for local or temporary material..."
git ls-files | grep -Ein '(^|/)(\.env|\.Rhistory|\.RData|__pycache__|\.cache)(/|$)|\.(bam|bai|fastq|fq|vcf|tif|tiff|fasta|rds)(\.gz)?$' || true

# 3. Identify local paths and drafting references in tracked text ----
echo "Checking tracked text files for local paths and drafting references..."
git grep -nEI '(/home/|/media/|codex://|chatgpt|openai|generated by ai)' -- ':!tools/preflight.sh' || true

echo "I review these matches manually before any public release."
